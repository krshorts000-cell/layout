import gzip
import base64
import os

def create_gmd(level_name="AutoGeneratedLayout", author="Creator", obstacle_count=30, bpm=128.0):
    # Заголовок уровня Geometry Dash 2.2
    header = "kS38,1_40_2_125_3_255_11_255_12_255_13_255_4_-1_6_-1_7_1_15_1_18_0_19_0_20_0,kA13,0,kA15,0,kA16,0,kA14,0,kA6,0,kA7,0,kA17,0,kA18,0,kS39,0;"
    
    # Скорость и расчет шага BPM (1x скорость = ~311.58 блоков/сек)
    speed = 311.58
    ground_y = 105.0
    seconds_per_beat = 60.0 / bpm
    units_per_beat = seconds_per_beat * speed
    
    objects = []
    current_x = 350.0
    
    for i in range(obstacle_count):
        current_x += units_per_beat
        pattern = i % 4
        
        if pattern == 0:
            # Одиночный шип (ID: 8)
            objects.append(f"1,8,2,{int(current_x)},3,{int(ground_y)};")
        elif pattern == 1:
            # Двойной шип (ID: 8)
            objects.append(f"1,8,2,{int(current_x)},3,{int(ground_y)};")
            objects.append(f"1,8,2,{int(current_x + 30)},3,{int(ground_y)};")
            current_x += 30
        elif pattern == 2:
            # Шип и желтая сфера над ним (ID: 36)
            objects.append(f"1,8,2,{int(current_x)},3,{int(ground_y)};")
            objects.append(f"1,36,2,{int(current_x)},3,{int(ground_y + 55)};")
        elif pattern == 3:
            # Платформа (ID: 1) и шип внизу
            objects.append(f"1,8,2,{int(current_x)},3,{int(ground_y)};")
            objects.append(f"1,1,2,{int(current_x)},3,{int(ground_y + 60)};")
            objects.append(f"1,1,2,{int(current_x + 30)},3,{int(ground_y + 60)};")
            current_x += 30

    # Полная строка данных уровня
    level_string = header + "".join(objects)
    
    # Сжатие Gzip + Base64 кодирование
    compressed = gzip.compress(level_string.encode('utf-8'))
    b64_level_data = base64.urlsafe_b64encode(compressed).decode('utf-8')
    b64_desc = base64.b64encode(f"Generated layout synced to {bpm} BPM".encode('utf-8')).decode('utf-8')
    
    # XML Plist формат .gmd (стандарт GDShare / Mega Hack)
    gmd_content = f"""<?xml version="1.0"?>
<plist version="1.0" gjver="2.0">
    <dict>
        <key>kCEK</key>
        <i>4</i>
        <key>k2</key>
        <s>{level_name}</s>
        <key>k3</key>
        <s>{b64_desc}</s>
        <key>k4</key>
        <s>{b64_level_data}</s>
        <key>k5</key>
        <s>{author}</s>
        <key>k8</key>
        <i>0</i>
        <key>k18</key>
        <i>0</i>
        <key>k19</key>
        <i>0</i>
        <key>k21</key>
        <i>2</i>
        <key>k50</key>
        <i>42</i>
    </dict>
</plist>"""

    output_filename = f"{level_name}.gmd"
    with open(output_filename, "w", encoding="utf-8") as f:
        f.write(gmd_content)
        
    print(f"[OK] Файл {output_filename} успешно создан! (Объектов: {len(objects)})")
    return output_filename

if __name__ == "__main__":
    create_gmd("LayoutBPM128", author="CreativeDev", obstacle_count=40, bpm=128.0)
